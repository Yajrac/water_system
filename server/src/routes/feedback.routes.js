import { Router } from 'express';
import { authenticate } from '../middleware/authenticate.js';
import { requireRole } from '../middleware/require-role.js';
import * as service from '../services/consumer.service.js';
import { unreadFeedback, readFeedback } from '../services/feedback-read.service.js';
const router=Router();
router.use(authenticate,requireRole('admin'));
router.get('/unread',async(req,res)=>res.json({success:true,data:await unreadFeedback(req.user.id)}));
router.post('/:id/read',async(req,res)=>res.json({success:true,data:await readFeedback(req.params.id,req.user.id)}));
router.get('/',async(req,res)=>res.json({success:true,data:await service.adminFeedback(req.query)}));
router.patch('/:id',async(req,res)=>res.json({success:true,data:await service.updateFeedback(req.params.id,req.body,req.user.id)}));
export default router;
