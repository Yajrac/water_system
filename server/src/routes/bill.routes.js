import { Router } from 'express';
import { syncLateFees } from '../middleware/sync-late-fees.js';
import { authenticate } from '../middleware/authenticate.js';
import { requireRole } from '../middleware/require-role.js';
import { previewBills, generateBills, listBills } from '../controllers/bill.controller.js';
const router = Router();
router.use(authenticate, requireRole('admin'), syncLateFees);
router.get('/', listBills);
router.post('/preview', previewBills);
router.post('/generate', generateBills);
export default router;
